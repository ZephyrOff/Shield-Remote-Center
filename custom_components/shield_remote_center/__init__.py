"""The Shield Media integration."""

from __future__ import annotations

from homeassistant.config_entries import ConfigEntry
from homeassistant.const import CONF_HOST, CONF_PORT, Platform
from homeassistant.core import HomeAssistant
from homeassistant.helpers.aiohttp_client import async_get_clientsession

from .client import ShieldClient
from .const import CONF_TOKEN

PLATFORMS = [Platform.MEDIA_PLAYER]

type ShieldConfigEntry = ConfigEntry[ShieldClient]


async def async_setup_entry(hass: HomeAssistant, entry: ShieldConfigEntry) -> bool:
    """Set up from a config entry. The entity stays unavailable until the Shield answers."""
    client = ShieldClient(
        async_get_clientsession(hass),
        entry.data[CONF_HOST],
        entry.data[CONF_PORT],
        entry.data[CONF_TOKEN],
    )
    client.start()
    entry.runtime_data = client
    await hass.config_entries.async_forward_entry_setups(entry, PLATFORMS)
    return True


async def async_unload_entry(hass: HomeAssistant, entry: ShieldConfigEntry) -> bool:
    """Unload a config entry."""
    unloaded = await hass.config_entries.async_unload_platforms(entry, PLATFORMS)
    if unloaded:
        await entry.runtime_data.stop()
    return unloaded
